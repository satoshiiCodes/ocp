// Verifies that every page the user asked for sweetalerts on actually shows one.
//
//   node test-alert-pages.mjs
//
// Two reporting styles are in play, and they need different tests:
//
//   session + redirect   the handler stores the message and redirects; the redirected GET
//                        has to read it back. Tested by posting something the handler
//                        refuses, then landing on the page in a real browser.
//   in place             the handler sets $swal_data and the same request re-renders.
//                        Tested by submitting the page's own form, which navigates the
//                        browser to the answer and runs its scripts.
//
// A plain fetch of the answer is not enough for the second kind: the scripts of a fetched
// document never run, so no alert would be seen even when the page is correct.
//
// Nothing is created: every submission is one the handler refuses, and the row counts are
// compared before and after.
import { withBrowser, db } from './browser.mjs';

const problems = [];
const log = [];

await withBrowser(async ({ go, goForAlert, ev, post }) => {
  const cases = [
    // ------------------------------------------------ session + redirect
    {
      label: 'spare_parts.php (add, refused)',
      page: 'spare_parts.php',
      table: 'spare_parts',
      style: 'redirect',
      fields: { part_number: '', part_name: '', unit_of_measure: '' },
    },
    {
      label: 'items_categories.php (add, refused)',
      page: 'items_categories.php',
      table: 'items_categories',
      style: 'redirect',
      fields: { category_name: '', description: '' },
    },
    {
      label: 'warehouses.php (add, refused)',
      page: 'warehouses.php',
      table: 'warehouses',
      style: 'inplace',
      fields: { warehouse_name: '', location: '' },
    },
    {
      label: 'purchase_request_spare_parts.php (create, refused)',
      page: 'purchase_request_spare_parts.php',
      table: 'spare_parts_pr',
      style: 'inplace',
      fields: { request_type: 'stock', create_pr: '1' },
    },
    // ------------------------------------------------ in place
    {
      label: 'employee_registration.php (update, refused)',
      page: 'employee_registration.php',
      table: 'employee',
      style: 'inplace',
      fields: { update_employee_details: '1', employee_id: '', firstname: '', lastname: '', position: '', hire_date: '' },
    },
  ];

  for (const c of cases) {
    const before = Number(db(`SELECT COUNT(*) FROM ${c.table}`));
    await go(c.page);

    let alerts = [];
    if (c.style === 'redirect') {
      await post(c.page, c.fields);
      // The alert only exists on the page the handler redirects to, and it is consumed by the
      // first load that reads it - so there is exactly one chance to catch it. A single
      // navigate is enough, but the page's own script can still be settling when goForAlert
      // gives up, and a missed alert then looks exactly like no alert. Loading it twice would
      // lose the message, so instead the same load is given more room.
      alerts = await goForAlert(c.page, 20000);
      if (!Array.isArray(alerts) || !alerts.length) {
        // one retry, by posting again: the message is regenerated by the handler
        await post(c.page, c.fields);
        alerts = await goForAlert(c.page, 20000);
      }
    } else {
      // submit the page's own form so the browser navigates and runs the answer's scripts
      await ev(`
        (() => {
          window.__alerts = [];
          const f = document.createElement('form');
          f.method = 'POST'; f.action = ${JSON.stringify(c.page)}; f.style.display = 'none';
          for (const [k, v] of Object.entries(${JSON.stringify(c.fields)})) {
            const i = document.createElement('input'); i.name = k; i.value = v; f.appendChild(i);
          }
          document.body.appendChild(f); f.submit();
          return 'submitted';
        })()
      `);
      await new Promise(r => setTimeout(r, 3600));
      alerts = await ev('window.__alerts');
    }

    const shown = (Array.isArray(alerts) ? alerts : []).map(a => { try { return JSON.parse(a); } catch { return null; } }).filter(Boolean);
    const after = Number(db(`SELECT COUNT(*) FROM ${c.table}`));
    if (after !== before) problems.push(`${c.label}: the submission created data (${before} -> ${after})`);

    if (!shown.length) {
      log.push(`${c.label.padEnd(46)} NO alert`);
      problems.push(`${c.label}: no SweetAlert`);
      continue;
    }
    const o = shown[0];
    const hasContent = Boolean(o.title || o.html || o.text);
    log.push(`${c.label.padEnd(46)} icon=${JSON.stringify(o.icon ?? '')} title=${JSON.stringify(o.title ?? '')} text=${JSON.stringify(String(o.text ?? '').slice(0, 30))}`);
    if (!hasContent) problems.push(`${c.label}: the alert had no title or text (only an OK button)`);
  }
});

for (const l of log) console.log('  ' + l);
console.log(`\nproblems: ${problems.length}`);
for (const p of problems) console.log('  X ' + p);
process.exit(problems.length ? 1 : 0);
