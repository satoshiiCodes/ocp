/**
 * Format employee name in "LAST, FIRST M. SUFFIX" format (all caps)
 */
function formatEmployeeName($firstname, $middlename, $lastname, $suffix) {
    $name = strtoupper($lastname . ', ' . $firstname);
    if (!empty($middlename)) {
        $name .= ' ' . strtoupper(substr($middlename, 0, 1)) . '.';
    }
    if (!empty($suffix)) {
        $name .= ' ' . strtoupper($suffix);
    }
    return $name;
}

