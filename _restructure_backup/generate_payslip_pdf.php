/**
 * Calculate late deduction based on minutes late and daily rate
 * Formula: (Daily Rate / 8 hours) / 60 * Late Minutes
 */
function calculateLateDeduction($daily_rate, $late_minutes) {
    if ($daily_rate <= 0 || $late_minutes <= 0) {
        return 0;
    }
    // Assuming 8-hour work day
    // Calculate per minute rate: (Daily Rate / 8 hours) / 60 minutes
    $per_minute_rate = ($daily_rate / 8) / 60;
    return $per_minute_rate * $late_minutes;
}

/**
 * Calculate overtime pay based on minutes overtime and daily rate
 * Formula: (Daily Rate / 8 hours) / 60 * Overtime Minutes
 */
function calculateOvertimePay($daily_rate, $overtime_minutes) {
    if ($daily_rate <= 0 || $overtime_minutes <= 0) {
        return 0;
    }
    // Assuming 8-hour work day
    // Calculate per minute rate: (Daily Rate / 8 hours) / 60 minutes
    $per_minute_rate = ($daily_rate / 8) / 60;
    return $per_minute_rate * $overtime_minutes;
}

/**
 * Get effective wage for an employee during a specific period
 * Checks wage_history for any wage changes during the period
 */
function getEffectiveWage($pdo, $employee_id, $period_start, $period_end) {
    try {
        // First, get the current wage from employee table
        $stmt = $pdo->prepare("SELECT daily_wage FROM employee WHERE id = :id");
        $stmt->execute([':id' => $employee_id]);
        $employee = $stmt->fetch(PDO::FETCH_ASSOC);
        $current_wage = floatval($employee['daily_wage'] ?? 0);
        
        // Check wage_history for any changes during this period
        $historyStmt = $pdo->prepare("
            SELECT new_wage, effectivity_date 
            FROM wage_history 
            WHERE employee_id = :employee_id 
            AND effectivity_date <= :period_end
            ORDER BY effectivity_date DESC 
            LIMIT 1
        ");
        
        $historyStmt->execute([
            ':employee_id' => $employee_id,
            ':period_end' => $period_end
        ]);
        
        $history = $historyStmt->fetch(PDO::FETCH_ASSOC);
        
        // If there's a wage change that took effect during or before this period, use that
        if ($history && strtotime($history['effectivity_date']) <= strtotime($period_end)) {
            return floatval($history['new_wage']);
        }
        
        return $current_wage;
        
    } catch (PDOException $e) {
        error_log("Error getting effective wage: " . $e->getMessage());
        return 0;
    }
}

/**
 * Get wage for a specific employee on a specific date
 */
function getEmployeeWageOnDate($pdo, $employee_id, $attendance_date) {
    try {
        $sql = "
            SELECT new_wage as daily_rate
            FROM wage_history
            WHERE employee_id = :employee_id
            AND effectivity_date <= :attendance_date
            ORDER BY effectivity_date DESC
            LIMIT 1
        ";
        
        $stmt = $pdo->prepare($sql);
        $stmt->bindParam(':employee_id', $employee_id);
        $stmt->bindParam(':attendance_date', $attendance_date);
        $stmt->execute();
        
        $result = $stmt->fetch(PDO::FETCH_ASSOC);
        
        if ($result && isset($result['daily_rate'])) {
            return floatval($result['daily_rate']);
        }
        
        // If no wage history found, get the current daily wage from employee table
        $stmt = $pdo->prepare("SELECT daily_wage FROM employee WHERE id = :id");
        $stmt->bindParam(':id', $employee_id);
        $stmt->execute();
        $current_wage = $stmt->fetch(PDO::FETCH_ASSOC);
        
        return $current_wage ? floatval($current_wage['daily_wage']) : 0.00;
        
    } catch(PDOException $e) {
        error_log("Error fetching wage for employee $employee_id on $attendance_date: " . $e->getMessage());
        return 0.00;
    }
}

/**
 * Get employee deductions effective during the specified period
 */
function getEmployeeDeductions($pdo, $employee_id, $period_start, $period_end) {
    $deductions = [];
    
    try {
        // Get all deductions that are effective during this period
        $stmt = $pdo->prepare("
            SELECT * FROM employee_deductions 
            WHERE employee_id = :employee_id
            AND (
                (effectivity_date BETWEEN :period_start AND :period_end)
                OR (effectivity_date <= :period_end AND effectivity_date IS NOT NULL)
            )
            AND (
                (from_date IS NULL AND to_date IS NULL)
                OR (from_date <= :period_end AND (to_date IS NULL OR to_date >= :period_start))
            )
            ORDER BY deduction_type, effectivity_date
        ");
        
        $stmt->execute([
            ':employee_id' => $employee_id,
            ':period_start' => $period_start,
            ':period_end' => $period_end
        ]);
        
        $deductions = $stmt->fetchAll(PDO::FETCH_ASSOC);
        
        // Group deductions by type and calculate total
        $grouped_deductions = [];
        foreach ($deductions as $deduction) {
            $type = $deduction['deduction_type'];
            if (!isset($grouped_deductions[$type])) {
                $grouped_deductions[$type] = [
                    'type' => $type,
                    'amount' => 0,
                    'items' => []
                ];
            }
            $grouped_deductions[$type]['amount'] += floatval($deduction['amount']);
            $grouped_deductions[$type]['items'][] = $deduction;
        }
        
        return array_values($grouped_deductions);
        
    } catch (PDOException $e) {
        error_log("Error getting employee deductions: " . $e->getMessage());
        return [];
    }
}

